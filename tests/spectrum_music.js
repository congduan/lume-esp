/* r97: math half uses the app's plain logic; integration half uses firmware prelude. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { performance } = require('node:perf_hooks');
const { runApp } = require('./lib/prelude_runner');
const APP = fs.readFileSync('examples/spectrum_music/app.js', 'utf8');
const source = APP.split('/* GAME UI */')[0];
const logic = vm.createContext({ Float32Array, DataView, ArrayBuffer, Math });
vm.runInContext(source, logic);
assert.ok(Number.isFinite(logic.smWindowSum) && logic.smWindowSum > 0);
assert.ok([...logic.smWindow].every(Number.isFinite));
console.log('PASS Hann window finite, coherent sum=' + logic.smWindowSum.toFixed(2));
const ui = runApp(APP, { audio: { _recordStream: () => -3 } });
assert.equal(ui.ctx.smMode, 'DEMO');
ui.ctx.smTick();
assert.ok(ui.messages.some(m => m[0] === 'draw' && String(m).includes('MIC OFF')));
console.log('PASS prelude starts DEMO after microphone error');
for (let i = 0; i < 1024; i++) ui.ctx.smPush(0.8 * Math.sin(2 * Math.PI * 32 * i / 1024));
assert.equal(ui.ctx.smAnalyze(), true);
assert.ok([...ui.ctx.smMagnitude].every(Number.isFinite));
let peak = 2;
for (let i = 3; i < 512; i++) if (ui.ctx.smMagnitude[i] > ui.ctx.smMagnitude[peak]) peak = i;
assert.equal(peak, 32);
assert.equal(ui.ctx.smBandForBin(peak), ui.ctx.smBandForBin(32));
assert.ok(ui.ctx.smBands[ui.ctx.smBandForBin(32)] > 0.7);
console.log('PASS native-API stub FFT finite; sine peak bin=' + peak + ' band=' + ui.ctx.smBandForBin(peak));
for (let i = 0; i < 39; i++) assert.ok(Math.abs(ui.ctx.smAngle(i + 1, 0) - ui.ctx.smAngle(i, 0) - 2 * Math.PI / 40) < 1e-12);
console.log('PASS radial index to angle linear');
const before = ui.messages.length;
ui.ctx.smTick();
const frame = ui.messages.slice(before);
const calls = frame.filter(m => m[0] === 'draw').length + frame.filter(m => m[0] === 'batch').reduce((n,m) => n + m[2].length / 6, 0);
assert.ok(calls <= 200, 'draw calls=' + calls);
assert.ok(ui.ctx.smLevel > 0 && ui.ctx.smBands.some(x => x > 0));
console.log('PASS DEMO audible PCM and visible FFT, draw calls=' + calls);
const mic = runApp(APP, { audio: { _recordStream: n => { assert.equal(n, 1024); return 0; } } });
const count = mic.messages.length;
const pcm = new ArrayBuffer(1024 * 4), view = new DataView(pcm);
for (let i = 0; i < 1024; i++) view.setInt16(i * 4, Math.round(24000 * Math.sin(2 * Math.PI * 24 * i / 1024)), true);
mic.ctx.__lume_dispatchAudioChunk(pcm, 1024);
assert.equal(mic.messages.length, count, 'callback must not draw or create text');
assert.equal(mic.ctx.smDirty(), 1);
mic.ctx.smTick();
assert.ok(mic.ctx.smLevel > 0);
console.log('PASS MIC callback defers analysis and drawing');
const times = [];
for (let trial = 0; trial < 5; trial++) {
  const start = performance.now();
  for (let i = 0; i < 100; i++) mic.ctx.smAnalyze();
  times.push((performance.now() - start) / 100);
}
times.sort((a,b) => a-b);
console.log('BENCH host prelude FFT+window+magnitude+bands 1024: median ' + times[2].toFixed(3) + ' ms/analysis, 5x100');
console.log('ALL SPECTRUM MUSIC CASES PASSED');
