// --- 1x1: shape, type and exact RGB565 bit pattern --------------------------
var d1 = lume.image.decode(buf(PNG1));
check(typeof d1 === 'object' && d1 !== null, '1x1 result is object');
check(d1.width === 1 && d1.height === 1, '1x1 dimensions');
check(Object.prototype.toString.call(d1.pixels) === '[object Uint16Array]', 'pixels is Uint16Array');
check(d1.pixels.length === 1 && d1.pixels[0] === 0xf800, '1x1 red = 0xf800, got ' + hex(d1.pixels));
var bytes1 = new Uint8Array(d1.pixels.buffer);
check(bytes1[0] === 0x00 && bytes1[1] === 0xf8, 'little-endian RGB565 colour plane');
print('PASS 1x1 PNG -> {1,1,Uint16Array(1)}, red 0xf800, LE bytes 00 f8');

// --- 2x2: four exact colours, byte order, alpha plane dropped --------------
var d2 = lume.image.decode(buf(PNG2));
check(d2.width === 2 && d2.height === 2, '2x2 dimensions');
check(d2.pixels.length === 4, '2x2 pixel count');
var expect2 = [0xf800, 0x07e0, 0x001f, 0xffff];
for (var i = 0; i < 4; i++) check(d2.pixels[i] === expect2[i], '2x2 bit ' + i + ': ' + hex(d2.pixels) + ' vs ' + hex(expect2));
var da = lume.image.decode(buf(PNG2A));
check(da.pixels.length === 4, 'A8 plane dropped from pixels length');
for (i = 0; i < 4; i++) check(da.pixels[i] === expect2[i], 'alpha fixture colour plane bit ' + i);
print('PASS 2x2 PNG exact RGB565 ' + hex(d2.pixels) + '; A8 plane discarded');

// --- optional maxW/maxH: one-step resize via shared imgscale core ----------
var up = lume.image.decode(buf(PNG2), 4, 4);
check(up.width === 4 && up.height === 4 && up.pixels.length === 16, 'upscale shape');
var expectUp = [0xf800,0xf800,0x07e0,0x07e0, 0xf800,0xf800,0x07e0,0x07e0,
                0x001f,0x001f,0xffff,0xffff, 0x001f,0x001f,0xffff,0xffff];
for (i = 0; i < 16; i++) check(up.pixels[i] === expectUp[i], 'upscale bit ' + i + ': ' + hex(up.pixels));
var down = lume.image.decode(buf(PNG2), 1, 1);
check(down.width === 1 && down.height === 1 && down.pixels.length === 1, 'downscale shape');
check(down.pixels[0] === 0xffff, 'downscale nearest centre tap = 0xffff, got ' + hex(down.pixels));
print('PASS decode 2x2 -> 4x4 nearest + -> 1x1 centre tap');

// --- decode -> imgscale.scale chain (r84 consumer) -------------------------
var chainOut = new Uint16Array(4);
check(lume.imgscale.scale(d2.pixels, d2.width, d2.height, chainOut, 2, 2, 'nearest') === 0, 'chain scale status');
for (i = 0; i < 4; i++) check(chainOut[i] === expect2[i], 'chain bit ' + i);
print('PASS decode pixels fed into lume.imgscale.scale, bits preserved');

// --- error codes -----------------------------------------------------------
check(lume.image.decode() === -1, 'missing arg -1');
check(lume.image.decode([]) === -1, 'non-ArrayBuffer -1');
check(lume.image.decode(buf([1,2,3,4])) === -2, 'corrupt data -2');
check(lume.image.decode(buf(PNG2), 96) === -1, 'one dim only -1');
check(lume.image.decode(buf(PNG2), 0, 96) === -2, 'zero dim -2');
check(lume.image.decode(buf(PNG2), 16385, 96) === -2, 'over 16384 -2');
check(lume.image.decode(buf(PNG2), 2.5, 96) === -2, 'fractional dim -2');
check(lume.image.decode(buf(PNG2), Symbol('x'), 96) === -1, 'coercion error -1');
var big = new Uint8Array(PNG2); big[16] = 0x01; big[17] = 0xe1; /* width 481 */
check(lume.image.decode(big.buffer) === -2, 'over 480x480 rejected -2');
print('PASS error codes -1/-2 (type, dimensions, 480 cap, corrupt input)');
