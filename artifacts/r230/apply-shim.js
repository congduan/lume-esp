function migrate(name) {
  const path = `examples/${name}/app.js`;
  let src = fs.readFileSync(path, 'utf8');
  if (src.includes(MARKER)) return { name, status: 'already-migrated' };

  // 1) Special case: img_view uses SW/SH as the source-image dimensions
  //    (24x24), not screen dimensions. Rename them so the shim's screen
  //    SW/SH do not collide. Pure identifier rename: no behavior change.
  if (name === 'img_view') {
    src = src.replace(/\bSW\b/g, '__IMG_SW').replace(/\bSH\b/g, '__IMG_SH');
  }

  // 2) Rename every app-level global constructor call to its __A_* wrapper.
  //    \b prevents matching kbText(, retainImage(, drawImage(, etc.
  src = src.replace(/\b(View|Text|Button|Canvas|Image|List)\(/g, '__A_$1(');

  // 3) Special case: SafeArea hard-codes size:480, which would keep the
  //    480-logical inscribed square (center ~240) at native 466. Make the
  //    size screen-derived; at 480 this is literally size:480 (no-op).
  if (name === 'control_center' || name === 'launcher_grid') {
    const before = src;
    src = src.replace(/(lume\.ui\.shell\.SafeArea\(\{[^}]*?shape:\s*'round',\s*)size:\s*480(,?[^}]*?\}\))/, '$1size: SW$2');
    if (src === before) throw new Error(`${name}: SafeArea size:480 not found`);
  }

  // 4) Insert shim at top: it defines functions/vars only, no constructor
  //    calls at definition time, so every call site below sees the wrappers.
  src = SHIM + src;
  fs.writeFileSync(path, src);
  return { name, status: 'migrated', bytes: Buffer.byteLength(src) };
}

