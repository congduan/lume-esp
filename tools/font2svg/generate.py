import argparse
import json
import pathlib
import re

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.roundingPen import RoundingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
SUPPORTED = set("MLHVCSQTAZmlhvcsqtaz")


def outline(glyph_set, glyph_name, box):
    bounds_pen = BoundsPen(glyph_set)
    glyph_set[glyph_name].draw(bounds_pen)
    bounds = bounds_pen.bounds
    if bounds is None:
        raise ValueError(f"empty outline: {glyph_name}")
    left, bottom, right, top = bounds
    x, y, w, h = box
    scale = min(w / (right - left), h / (top - bottom))
    dx = x + (w - (right - left) * scale) / 2 - left * scale
    dy = y + (h - (top - bottom) * scale) / 2 + top * scale
    path_pen = SVGPathPen(glyph_set)
    rounded = RoundingPen(path_pen, roundFunc=lambda n: round(n, 2),
                          transformRoundFunc=lambda n: round(n, 2))
    glyph_set[glyph_name].draw(TransformPen(rounded, (scale, 0, 0, -scale, dx, dy)))
    path = path_pen.getCommands()
    commands = {c for c in path if c.isalpha()}
    if not commands <= SUPPORTED:
        raise ValueError(f"unsupported SVG command for {glyph_name}: {commands - SUPPORTED}")
    return path


def svg(paths):
    body = "".join(f'<path d="{p}" fill="#FFFFFF"/>' for p in paths)
    # r58 sizeOf needs intrinsic pixel dimensions in addition to viewBox.
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100" viewBox="0 0 100 100">{body}</svg>'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=pathlib.Path,
                        default=pathlib.Path("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"))
    parser.add_argument("--output", type=pathlib.Path,
                        default=ROOT / "examples/abc123/glyphs.js")
    args = parser.parse_args()
    font = TTFont(args.font)
    cmap = font.getBestCmap()
    glyph_set = font.getGlyphSet()
    names = {ch: cmap[ord(ch)] for ch in CHARS}
    glyphs = {ch: svg([outline(glyph_set, names[ch], (5, 5, 90, 90))]) for ch in CHARS}
    pairs = {upper: svg([
        outline(glyph_set, names[upper], (12, 3, 76, 44)),
        outline(glyph_set, names[upper.lower()], (12, 53, 76, 44)),
    ]) for upper in CHARS[:26]}
    header = ("/* Generated by tools/font2svg/generate.py from DejaVu Sans Bold.\n"
              " * DejaVu Fonts license (Bitstream Vera derivative):\n"
              " * https://dejavu-fonts.github.io/License.html\n"
              " * Rebuild: python3.12 tools/font2svg/generate.py\n"
              " * Static white fill; each outline is centered in a 100x100 viewBox.\n"
              " */\n")
    lines = [header, "export var GLYPHS = {\n"]
    lines += [f"  {json.dumps(ch)}: {json.dumps(glyphs[ch])},\n" for ch in CHARS]
    lines += ["};\n", "export var GLYPH_PAIRS = {\n"]
    lines += [f"  {json.dumps(ch)}: {json.dumps(pairs[ch])},\n" for ch in CHARS[:26]]
    lines += ["};\n"]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("".join(lines), encoding="utf-8")
    print(f"wrote {args.output}: {len(glyphs)} glyphs, {len(pairs)} pairs, {args.output.stat().st_size} bytes")


if __name__ == "__main__":
    main()
