/**
 * Embedded JS bundles for M1 (evaluated on the engine task after prelude).
 *
 * The strings are embedded as C literals (no filesystem load in M1). JS uses
 * single quotes throughout so no C escaping is needed; each line ends in \n.
 *
 * Prelude = signals (Preact-signals model) + declarative ui components.
 * Demo    = JS version of the button counter (roadmap M1 first half).
 */
#include "lume_scripts.h"

const char lume_prelude_js[] =
"/* ---- native binding constants (mirror lume_ui_bridge.h) ---- */\n"
"var NODE_VIEW = 0, NODE_TEXT = 1, NODE_BUTTON = 2;\n"
"var ATTR_TEXT = 0, ATTR_BG_COLOR = 1, ATTR_WIDTH = 2, ATTR_HEIGHT = 3,\n"
"    ATTR_ALIGN = 4, ATTR_VISIBLE = 5, ATTR_PARENT = 6;\n"
"var ALIGN_CENTER = 0, ALIGN_TOP_MID = 2, ALIGN_BOTTOM_MID = 4;\n"
"var TEXT_MAX = 63;\n"
"\n"
"/* ---- reactivity: minimal Preact-signals model (M1) ----\n"
" * Per-signal: value + version (ver) + subscription array (subs).\n"
" * Per-effect: dirty flag to avoid duplicate enqueue.\n"
" * set() enqueues subscribers then runs ONE batched drain (no microtask).\n"
" */\n"
"var __batch = [];\n"
"var __draining = false;\n"
"var __active = null;      /* effect currently running (dependency tracking) */\n"
"var __version = 0;        /* global version tick (versioned nodes) */\n"
"\n"
"function __subscribe(sig, eff) {\n"
"  if (sig._subs.indexOf(eff) < 0) sig._subs.push(eff);\n"
"}\n"
"function __enqueue(eff) {\n"
"  if (eff.dirty) return;   /* dirty flag: no duplicate enqueue */\n"
"  eff.dirty = true;\n"
"  __batch.push(eff);\n"
"}\n"
"function __drain() {\n"
"  if (__draining) return;  /* batches, not nested drains / no microtask */\n"
"  __draining = true;\n"
"  try {\n"
"    var guard = 0;\n"
"    while (__batch.length) {\n"
"      var eff = __batch.shift();\n"
"      eff.dirty = false;\n"
"      var prev = __active;\n"
"      __active = eff;\n"
"      try { eff.fn(); } finally { __active = prev; }\n"
"      if (++guard > 1024) break;\n"
"    }\n"
"  } finally {\n"
"    __draining = false;    /* never wedge the batch queue on a thrown effect */\n"
"  }\n"
"}\n"
"function signal(value) {\n"
"  var subs = [];\n"
"  var ver = 0;             /* per-signal version */\n"
"  function read() {\n"
"    if (__active) __subscribe(read, __active);  /* read == subscribe */\n"
"    return value;\n"
"  }\n"
"  read._subs = subs;\n"
"  read._ver = function () { return ver; };\n"
"  read.set = function (v) {\n"
"    if (v === value) return;             /* equality check: no propagation */\n"
"    value = v;\n"
"    ver++;\n"
"    __version++;\n"
"    for (var i = 0; i < subs.length; i++) __enqueue(subs[i]);\n"
"    __drain();                          /* single batched drain */\n"
"  };\n"
"  return read;\n"
"}\n"
"function effect(fn) {\n"
"  var eff = { fn: fn, dirty: false };\n"
"  var prev = __active;\n"
"  __active = eff;\n"
"  try { fn(); } finally { __active = prev; }   /* run once, auto-track deps */\n"
"  return eff;             /* M1: no dispose handle */\n"
"}\n"
"\n"
"/* ---- declarative UI ---- */\n"
"var __pressHandlers = {};  /* node_id -> js onPress callback */\n"
"\n"
"function __checkText(s) {\n"
"  if (typeof s !== 'string') s = String(s);\n"
"  if (s.length > TEXT_MAX) throw new Error('lume: text exceeds ' + TEXT_MAX + ' bytes');\n"
"  return s;               /* C binding enforces the 64-byte wire limit too */\n"
"}\n"
"function __bindText(id, text) {\n"
"  if (typeof text === 'function') {\n"
"    /* getter form: wrap in an effect so signal changes repaint the attr */\n"
"    effect(function () { lume.setAttr(id, ATTR_TEXT, __checkText(text())); });\n"
"  } else {\n"
"    lume.setAttr(id, ATTR_TEXT, __checkText(text === undefined ? '' : text));\n"
"  }\n"
"}\n"
"function __applyAttrs(id, p) {\n"
"  if (p.bg !== undefined) lume.setAttr(id, ATTR_BG_COLOR, p.bg);\n"
"  if (p.w !== undefined) lume.setAttr(id, ATTR_WIDTH, p.w);\n"
"  if (p.h !== undefined) lume.setAttr(id, ATTR_HEIGHT, p.h);\n"
"  lume.setAttr(id, ATTR_ALIGN, p.align === undefined ? ALIGN_CENTER : p.align);\n"
"  if (p.visible !== undefined) lume.setAttr(id, ATTR_VISIBLE, p.visible ? 1 : 0);\n"
"}\n"
"function View(props, children) {\n"
"  props = props || {};\n"
"  var id = lume.createNode(NODE_VIEW, props.parent || 0);\n"
"  __applyAttrs(id, props);\n"
"  if (children) {\n"
"    for (var i = 0; i < children.length; i++) {  /* append in order */\n"
"      lume.setAttr(children[i], ATTR_PARENT, id);\n"
"    }\n"
"  }\n"
"  return id;\n"
"}\n"
"function Text(props) {\n"
"  props = props || {};\n"
"  var id = lume.createNode(NODE_TEXT, props.parent || 0);\n"
"  __applyAttrs(id, props);\n"
"  if (props.text !== undefined) __bindText(id, props.text);\n"
"  return id;\n"
"}\n"
"function Button(props) {\n"
"  props = props || {};\n"
"  var id = lume.createNode(NODE_BUTTON, props.parent || 0);\n"
"  __applyAttrs(id, props);\n"
"  if (props.title !== undefined) __bindText(id, props.title);\n"
"  if (typeof props.onPress === 'function') {\n"
"    __pressHandlers[id] = props.onPress;\n"
"    lume.setPressEvent(id);\n"
"  }\n"
"  return id;\n"
"}\n"
"/* engine -> JS press dispatch (called from C via JS_Call) */\n"
"function __lume_dispatchPress(nodeId) {\n"
"  var h = __pressHandlers[nodeId];\n"
"  if (typeof h === 'function') h();\n"
"}\n";

const char lume_demo_js[] =
"/* ---- M1 demo: JS button counter ---- */\n"
"var count = signal(0);\n"
"View({ bg: 0x0B1E3F, w: 480, h: 480 }, [\n"
"  Text({ text: function () { return 'taps: ' + count(); } }),  /* centered big text */\n"
"  Button({ align: ALIGN_BOTTOM_MID, title: '+1',\n"
"           onPress: function () { count.set(count() + 1); } })\n"
"]);\n";
