#!/usr/bin/env python3
"""Generate the firmware's NUL-terminated C arrays from the JS source files."""

from pathlib import Path
import sys


SCRIPTS = (
    ("lume_prelude_js", "prelude.js"),
    ("lume_demo_js", "demo.js"),
    ("lume_home_js", "home.js"),
)

# Control bytes that have a short C escape. json.dumps uses \u00XX for the
# remaining 0x00-0x1f bytes, but GCC rejects universal character names below
# U+00A0 inside string literals ("not a valid universal character"), so those
# must be emitted as \xNN instead. The short forms below match json.dumps
# output, keeping existing generated files byte-identical.
_C_SHORT_ESCAPES = {
    '"': '\\"',
    '\\': '\\\\',
    '\n': '\\n',
    '\r': '\\r',
    '\t': '\\t',
    '\b': '\\b',
    '\f': '\\f',
}


def c_string(text: str) -> str:
    """Quote one source line as a C string literal with GCC-safe escapes."""
    out = []
    for i, ch in enumerate(text):
        short = _C_SHORT_ESCAPES.get(ch)
        if short is not None:
            out.append(short)
        elif ord(ch) < 0x20 or ord(ch) == 0x7f:
            out.append(f'\\x{ord(ch):02x}')
            # A C hex escape consumes every following hex digit; close the
            # literal so "\x01" + "a" cannot become the single byte 0x1a.
            following = text[i + 1] if i + 1 < len(text) else ''
            if following in '0123456789abcdefABCDEF':
                out.append('""')
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


def generate(source_dir: Path) -> str:
    parts = ["/* Generated by gen_lume_scripts.py; edit the prelude JS files. */\n"]
    for symbol, filename in SCRIPTS:
        data = (source_dir / filename).read_bytes()
        if b"\0" in data:
            raise ValueError(f"{filename} contains a NUL byte")
        script = data.decode("utf-8")
        parts.append(f"const char {symbol}[] =\n")
        parts.extend(c_string(line) + "\n"
                     for line in script.splitlines(keepends=True))
        parts.append(";\n\n")
    return "".join(parts)


if __name__ == "__main__":
    output = Path(sys.argv[1])
    content = generate(Path(sys.argv[2])).encode("utf-8")
    if not output.exists() or output.read_bytes() != content:
        output.write_bytes(content)
